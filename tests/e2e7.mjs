// Fase 7: immagini e velocità in V1, clip disattivate (anteprima ed esportazione), ricollegamento di immagini e audio
import { launch, BASE, MEDIA, check, TMP } from './helpers.mjs';
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
const { browser, page, errors, ctx } = await launch();
await ctx.addInitScript(() => { localStorage.setItem('engimedit:tourDone', 'true'); });
await page.goto(BASE + '#progetti');
await page.click('.dash-hero >> text=Nuovo progetto');
await page.waitForSelector('.ed');
await page.setInputFiles('.ed-lib input[type=file]', [MEDIA + 'Paesaggio.mp4', MEDIA + 'Foto.png', MEDIA + 'Voce.wav']);
await page.waitForFunction(() => document.querySelectorAll('.lib-item').length === 3 && !document.querySelector('.lib-item.loading'), null, { timeout: 30000 });
await page.waitForTimeout(1200);
await page.evaluate(() => { const e = App.view.editor; const A = Object.values(e.project.assets); const by = (n) => A.find((a) => a.name === n).id;
  e.addToTimeline([by('Foto.png'), by('Paesaggio.mp4'), by('Foto.png')]);
  const ids = e.clips.map((c) => c.id);
  e.commitSel('x', { out: 2 }, [ids[0]]);
  e.commitSel('x', { speed: 2 }, [ids[1]]);
  e.commitSel('x', { disabled: true }, [ids[2]]);
  e.seek(0); });
const tot = await page.evaluate(() => App.view.editor.total);
check(Math.abs(tot - 10) < 0.01, 'V1: immagine 2 s + video 6 s a 2× (3 s) + immagine 5 s = ' + tot);
await page.click('.btn-play'); await page.waitForTimeout(3800);
const st = await page.evaluate(() => { const e = App.view.editor; const c = document.querySelector('.stage-frame canvas'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let s = 0; for (let i = 0; i < d.length; i += 400) s += d[i] + d[i + 1] + d[i + 2]; return { t: e.t, playing: e.player.playing, pix: s, cur: e.player.vp.map((p) => [p.el.paused, p.el.playbackRate.toFixed(2), p.el.currentTime.toFixed(2)]) }; });
console.log('    ', JSON.stringify(st));
check(st.t > 3.2 && st.playing && st.pix > 1000, 'riproduzione: immagine → video a 2× senza blocchi');
await page.waitForTimeout(2200);
const st2 = await page.evaluate(() => { const e = App.view.editor; const c = document.querySelector('.stage-frame canvas'); const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let s = 0; for (let i = 0; i < d.length; i += 400) s += d[i] + d[i + 1] + d[i + 2]; return { t: e.t, pix: s }; });
console.log('    ', JSON.stringify(st2));
check(st2.t > 5 && st2.pix < 50, 'clip disattivata: fotogramma nero in riproduzione');
await page.keyboard.press(' ');
// esportazione con immagine, velocità 2×, clip disattivata
const out = await page.evaluate(async () => { const e = App.view.editor; const plan = await Exporter.plan(640, 360, 30, 2e6, true);
  const r = await Exporter.run({ project: e.project, W: 640, H: 360, fps: 30, vbr: 2e6, plan }, { stage() {}, progress() {}, signal: new AbortController().signal });
  const buf = new Uint8Array(await r.blob.arrayBuffer()); let s = ''; for (let i = 0; i < buf.length; i += 8192) s += String.fromCharCode(...buf.subarray(i, i + 8192)); return btoa(s); });
const f = TMP + '/engimedit-extra.mp4'; writeFileSync(f, Buffer.from(out, 'base64'));
const fr = spawnSync('ffprobe', ['-v', 'error', '-count_frames', '-select_streams', 'v', '-show_entries', 'stream=nb_read_frames', '-of', 'csv=p=0', f]).stdout.toString().trim();
check(fr === '300', 'esportazione con immagine, 2× e clip disattivata: 300 fotogrammi (' + fr + ')');
const lum = (ts) => { const raw = spawnSync('ffmpeg', ['-v', 'error', '-ss', String(ts), '-i', f, '-frames:v', '1', '-vf', 'scale=1:1', '-f', 'rawvideo', '-pix_fmt', 'gray', '-']).stdout; return raw[0]; };
console.log('     luminosità 1 s / 3 s / 7 s:', lum(1), lum(3), lum(7));
check(lum(1) > 40 && lum(3) > 40 && lum(7) < 8, 'immagine e video visibili, clip disattivata nera');
// relink: immagine e audio
const pid = await page.evaluate(async () => { const e = App.view.editor; e.seek(0); e.addToTimeline([Object.values(e.project.assets).find((a) => a.kind === 'audio').id]); await e.saveNow(); for (const id of Object.keys(e.project.assets)) await DB.del('media', id); return e.project.id; });
await page.goto(BASE + '#progetti'); await page.waitForSelector('.proj-card:not(.new)');
await page.goto(BASE + '#editor-' + pid);
await page.waitForSelector('dialog.modal >> text=Ritrova i tuoi video');
await page.setInputFiles('dialog input[type=file]', [MEDIA + 'Paesaggio.mp4', MEDIA + 'Foto.png', MEDIA + 'Voce.wav']);
await page.waitForSelector('dialog >> text=Fatto', { timeout: 20000 });
check((await page.$$('dialog .badge.ok')).length === 3, 'ritrova i file: video, immagine e audio ricollegati');
await page.click('dialog >> text=Fatto');
await page.waitForTimeout(800);
const ok = await page.evaluate(() => Object.keys(App.view.editor.project.assets).every((id) => Media.get(id).status === 'ready') && !!Media.get(Object.values(App.view.editor.project.assets).find((a) => a.kind === 'image').id).image);
check(ok, 'dopo il ricollegamento i file sono pronti');
const real = errors.filter((x) => !/GL Driver Message|willReadFrequently/.test(x));
console.log('ERRORI CONSOLE:', real);
check(!real.length, 'nessun errore in console');
await browser.close();
