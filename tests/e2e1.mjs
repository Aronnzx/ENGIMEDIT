// Fase 1: pagine, dashboard, creazione progetto, tutorial, importazione ed errori
import { launch, BASE, check, MEDIA, TMP } from './helpers.mjs';
const { browser, page, errors } = await launch();
await page.goto(BASE + '#home');
await page.waitForSelector('.lp-hero h1');
check((await page.textContent('.lp-hero h1')).includes('Monta il tuo primo video'), 'landing: titolo');
await page.screenshot({ path: 'test-results/01-landing.png' });
await page.screenshot({ path: 'test-results/01b-landing-full.png', fullPage: true });
await page.click('.lp-nav >> text=Apri EngimEdit');
await page.waitForSelector('.dash-hero');
check(await page.isVisible('text=Nessun progetto per ora'), 'dashboard: stato vuoto');
await page.screenshot({ path: 'test-results/02-dashboard-empty.png' });
await page.click('.dash-hero >> text=Nuovo progetto');
await page.waitForSelector('.ed');
await page.waitForSelector('.tour-pop', { timeout: 5000 });
check(await page.isVisible('.tour-pop >> text=Aggiungi un video'), 'tutorial: passo 1 visibile');
await page.screenshot({ path: 'test-results/03-editor-tour.png' });
await page.click('.tour-pop >> text=Avanti');
check(await page.isVisible('.tour-pop >> text=Trascinalo nella timeline'), 'tutorial: passo 2');
await page.click('.tour-pop >> text=Indietro');
await page.click('.tour-pop >> text=Salta');
check(!(await page.isVisible('.tour-pop')), 'tutorial: saltato');
await page.screenshot({ path: 'test-results/04-editor-empty.png' });
// importazione: file validi e non validi insieme
const dir = MEDIA;
await page.setInputFiles('.ed-lib input[type=file]', [dir + 'Paesaggio.mp4', dir + 'Verticale.mp4', dir + 'Barre.webm', dir + 'Muto.mp4', dir + 'Rotto.mp4', dir + 'appunti.txt']);
await page.waitForFunction(() => document.querySelectorAll('.lib-item').length === 4 && !document.querySelector('.lib-item.loading'), null, { timeout: 30000 });
check((await page.$$('.lib-item')).length === 4, 'importazione: 4 video validi in libreria');
await page.waitForSelector('.toast.ok', { timeout: 20000 });
const toasts = await page.$$eval('.toast.err .t-msg', (els) => els.map((e) => e.textContent));
console.log('     toast errori:', toasts);
check(toasts.some((x) => x.includes('Rotto.mp4')), 'errore chiaro per file danneggiato');
check(toasts.some((x) => x.includes('appunti.txt') && x.includes('non è un video')), 'errore chiaro per file non video');
await page.waitForTimeout(2500);
const meta = await page.$$eval('.lib-item', (els) => els.map((e) => e.querySelector('.li').textContent));
console.log('     metadati:', meta);
check(meta.some((m) => m.includes('1280×720') && m.includes('30 fps')), 'metadati: risoluzione e fps');
check(meta.some((m) => m.includes('Muto') && m.includes('Senza audio')), 'badge Senza audio');
await page.screenshot({ path: 'test-results/05-library.png' });
console.log('ERRORI CONSOLE:', errors);
await browser.close();
